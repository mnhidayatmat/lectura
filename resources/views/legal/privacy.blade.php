<x-legal-layout title="Privacy Policy" updated="7 October 2026">
    <p>This policy explains what personal data Lectura (the website at lectura.coursesme.com) and the Lectura Go app for iPhone and Android collect, why, and what you can do about it. Lectura is operated by Mohamad Nur Hidayat Mat in Malaysia ("we"), and we handle personal data in line with Malaysia's Personal Data Protection Act 2010.</p>

    <p>Lectura is used by universities and polytechnics. If your institution set up your account, it decides which courses you are in and what your lecturers can see, and you should also read its own privacy notice.</p>

    <h2>What we collect</h2>
    <ul>
        <li><strong>Account details:</strong> your name, email address, password (stored only as a hash), profile photo, and your Google or Apple account identifier if you sign in with them. If you use Sign in with Apple and hide your email, we receive Apple's relay address instead.</li>
        <li><strong>Institution details:</strong> your institution, role (student, lecturer, coordinator or admin), student ID number, and the courses, sections and groups you belong to.</li>
        <li><strong>Class activity:</strong> attendance check-ins (time, status, and the IP address and device type used to check in), quiz and live-session answers, assignment and assessment submissions with the files and photos you upload, marks and feedback, absence excuses, and messages, files, tasks and minutes in group workspaces.</li>
        <li><strong>Viewing progress:</strong> for lecture episodes, how far you watched, when, the scenes you replayed, and your Quick Check answers.</li>
        <li><strong>Device data:</strong> a push notification token for your device, so we can send you notifications you can turn off in your phone's settings.</li>
    </ul>
    <p>The app uses your camera only to scan attendance QR codes and to photograph work you choose to submit, and your photo library only when you pick a photo to upload. We do not collect your location, contacts or browsing history, we do not show advertising, and we do not track you across other companies' apps or websites.</p>

    <h2>Why we use it</h2>
    <ul>
        <li>To run your classes: attendance, quizzes, materials, submissions, marking and feedback.</li>
        <li>To show your lecturers and your institution the records they need to teach and assess you.</li>
        <li>To send notifications about classes, new work, released marks and reminders.</li>
        <li>To keep the service secure, for example by limiting repeated sign-in attempts.</li>
    </ul>

    <h2>Who we share it with</h2>
    <p>We do not sell personal data. Within Lectura, your lecturers and your institution's administrators see the records for the courses they are responsible for. We use these service providers to run Lectura:</p>
    <ul>
        <li>Our hosting and file storage providers, which store the database and uploaded files.</li>
        <li>Google Firebase Cloud Messaging and Apple Push Notification service, to deliver notifications.</li>
        <li>Google and Apple, when you choose to sign in with them.</li>
        <li>Google Drive, only if a lecturer connects their own Drive to store course files.</li>
        <li>AI providers (Anthropic, OpenAI or Google), only when a lecturer uses AI-assisted features such as marking suggestions. Submissions sent to them are used to produce the suggestion, and the lecturer decides the final mark.</li>
        <li>YouTube, which plays lecture episodes your lecturer published on YouTube under YouTube's own privacy policy.</li>
    </ul>

    <h2>How long we keep it</h2>
    <p>We keep your data while your account is active and while your institution needs your academic records. When you delete your account, we delete your personal account details; records that belong to your institution, such as marks and attendance, may be kept by the institution as required by its own policies.</p>

    <h2>Your choices and rights</h2>
    <ul>
        <li>You can see and correct your profile in the app or on the web.</li>
        <li>You can delete your account at any time from Profile in the app or on the web. If you signed in with Apple, we also revoke Lectura's access to your Apple account.</li>
        <li>You can ask us for a copy of your personal data, or ask us to correct or delete it, by emailing us.</li>
    </ul>

    <h2>Children</h2>
    <p>Lectura is meant for students in higher education and their lecturers, and is not directed at children under 13.</p>

    <h2>Changes</h2>
    <p>If we change this policy, we will update the date above, and tell you in the app for significant changes.</p>

