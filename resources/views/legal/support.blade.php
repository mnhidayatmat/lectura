    <h2>Common questions</h2>

    <p><strong>How do I sign in?</strong><br>Use the email and password of your Lectura account, or Continue with Google or Apple. The app uses the same account as the website.</p>

    <p><strong>How do I join a course?</strong><br>Ask your lecturer for the section invite code, then choose Join course in the app and enter it.</p>

    <p><strong>The QR code won't scan.</strong><br>Allow camera access for Lectura Go in your phone's Settings. The code changes every few seconds, so scan the one currently on screen. If you are offline, the check-in is queued and sent when you reconnect.</p>

    <p><strong>I'm not getting notifications.</strong><br>Turn on notifications for Lectura Go in your phone's Settings, then sign out and back in.</p>

    <p><strong>How do I delete my account?</strong><br>Open Profile in the app, or on the web, and choose Delete account. See our <a href="{{ route('privacy') }}">Privacy Policy</a> for what happens to your data.</p>
